/** Union of legacy SPICe+ REQUESTS plus FORM_REQUESTS, used by the Forms hub. */
export function allRequests(): ClientRequest[] {
  // Treat legacy REQUESTS as SPICE_PART_A unless they already have formType.
  const legacyWithFormType = REQUESTS.map(r => ({
    ...r,
    formType: r.formType ?? ("SPICE_PART_A" as FormType),
  }));
  return [...FORM_REQUESTS, ...legacyWithFormType];
}

export function formRequestsForUser(
  role: "ADMIN" | "SUPERADMIN",
  name: string,
  formType?: FormType
): ClientRequest[] {
  const base = allRequests();
  const filtered = formType ? base.filter(r => r.formType === formType) : base;
  if (role === "SUPERADMIN") return filtered;
  return filtered.filter(r => r.assignedAdmin === name || !r.assignedAdmin);
}
